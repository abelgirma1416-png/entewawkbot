def rule_pages(max_length: int = 3500) -> list[str]:
    """Split on paragraph boundaries so each Telegram message stays under its limit."""
    pages: list[str] = []
    page = ""
    for paragraph in RULES_TEXT.split("\n\n"):
        candidate = f"{page}\n\n{paragraph}".strip()
        if page and len(candidate) > max_length:
            pages.append(page)
            page = paragraph
        else:
            page = candidate
    if page:
        pages.append(page)
    return pages
